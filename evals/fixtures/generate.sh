#!/bin/bash
# Regenerates the synthetic *.ts benchmark fixtures under evals/fixtures/.
#
# These are synthetic example code files, not real production code, sized
# to cross SHUNT_MIN_LINES (default 350) so evals/benchmarks.json exercises
# genuine delegation. Generation is deterministic (same verbs/nouns in the
# same order every run), so the fixtures are reproducible; re-run this after
# editing the word lists below rather than hand-editing the .ts files.
#
# Usage: evals/fixtures/generate.sh

set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

VERBS=(fetch create update delete list sync validate parse serialize deserialize
       connect disconnect retry cache invalidate refresh publish subscribe archive restore)
NOUNS=(User Order Product Session Token Config Metric Event Task Record
       Batch Job Schedule Report Invoice Payment Shipment Profile Comment Notification)

n_verbs=${#VERBS[@]}
n_nouns=${#NOUNS[@]}

method_block() {
  local class="$1" i="$2"
  local verb="${VERBS[$((i % n_verbs))]}"
  local noun="${NOUNS[$((i / n_verbs % n_nouns))]}"
  local name="${verb}${noun}"
  cat <<EOF

  /**
   * ${verb}s a ${noun} by id. Synthetic benchmark fixture method.
   */
  async ${name}(id: string): Promise<${noun}> {
    this.logger.debug(\`${class}.${name} called with id=\${id}\`);
    const response = await this.http.request('POST', \`/${noun,,}s/\${id}\`);
    if (!response.ok) {
      throw new ApiError(\`${name} failed: \${response.status}\`);
    }
    return response.data as ${noun};
  }
EOF
}

test_block() {
  local class="$1" i="$2"
  local verb="${VERBS[$((i % n_verbs))]}"
  local noun="${NOUNS[$((i / n_verbs % n_nouns))]}"
  local name="${verb}${noun}"
  cat <<EOF

  it('${name} returns the ${noun} from the http client', async () => {
    const http = new FakeHttpClient({ ok: true, data: { id: '1' } });
    const ${class,,} = new ${class}(http, new NullLogger());
    const result = await ${class,,}.${name}('1');
    expect(result).toEqual({ id: '1' });
  });
EOF
}

generate_class_file() {
  local out="$1" class="$2" count="$3"
  {
    echo "// Synthetic benchmark fixture. Generated by evals/fixtures/generate.sh."
    echo "// Not real production code; exists only to exercise bulk-read delegation."
    echo ""
    echo "import { ApiError } from './errors';"
    echo "import type { HttpClient } from './http-client';"
    echo "import type { Logger } from './logger';"
    echo ""
    echo "export class ${class} {"
    echo "  constructor(private readonly http: HttpClient, private readonly logger: Logger) {}"
    for ((i = 0; i < count; i++)); do
      method_block "$class" "$i"
    done
    echo "}"
  } > "$out"
}

generate_test_file() {
  local out="$1" class="$2" count="$3"
  {
    echo "// Synthetic benchmark fixture. Generated by evals/fixtures/generate.sh."
    echo "// Not real production code; exists only to exercise bulk-read delegation."
    echo ""
    echo "import { describe, it, expect } from 'vitest';"
    echo "import { ${class} } from './${class,,}';"
    echo "import { FakeHttpClient } from './test-helpers/fake-http-client';"
    echo "import { NullLogger } from './test-helpers/null-logger';"
    echo ""
    echo "describe('${class}', () => {"
    for ((i = 0; i < count; i++)); do
      test_block "$class" "$i"
    done
    echo "});"
  } > "$out"
}

generate_class_file "$DIR/api-client.ts" "ApiClient" 55
generate_class_file "$DIR/task-queue.ts" "TaskQueue" 20
generate_test_file  "$DIR/task-queue.test.ts" "TaskQueue" 20
generate_class_file "$DIR/event-bus.ts" "EventBus" 28

wc -l "$DIR"/*.ts
